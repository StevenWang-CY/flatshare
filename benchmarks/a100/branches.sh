#!/usr/bin/env bash
# branches.sh stage BASE HEAD | run [--flags "FLAG..."]: the A100 run's optional arm 2 (docs/BENCHMARKS.md, the optional
# arms, P-1's pair), on this host: the PRs' own code, vLLM at HEAD (the stacked PRs' tip) with their switches on against
# vLLM at BASE (main, where the PRs branch off) as it is, where the core measured make-room, their port onto vLLM
# 0.32.0.
#   stage  before the billed clock: a clone of the fork (StevenWang-CY/vllm, which carries the PR branches) at
#          ~/flatshare/vendor/vllm, a worktree of each commit, and a venv of each, venvs/branch-base and
#          venvs/branch-head: a Python-only install over the precompiled binaries of its upstream merge base
#          (VLLM_USE_PRECOMPILED=1, vLLM's documented path for Python changes), with the torch build of the node's
#          install path; then each env's own parser reads the node's engine.yaml, and HEAD's knows the PRs' flags
#   run    for each env, a node variant whose engine runs from it (~/flatshare/node/variants/branch-NAME), BASE with
#          no flag and HEAD with --flags (the PRs' values: at most 2 preemptions a step, the budget cap with a 48-token
#          window): make-room's KV case x3, the prefill case x2 and the calls' tail x2 each, into
#          ~/flatshare/runs/a100/branches/ (as probes.sh writes, a run done before kept)
# BASE and HEAD are the commits the PR bodies name at the run's time; the main session gives them.
set -euo pipefail
action=${1:-}
[[ $action == stage || $action == run ]] ||
  { echo "usage: branches.sh stage BASE HEAD | run [--flags \"FLAG...\"]" >&2; exit 2; }
root=$HOME/flatshare
src=$(cd "$(dirname "$0")/../.." && pwd)
node=${FLATSHARE_NODE_DIR:-$root/node}
uv=${UV:-$HOME/.local/bin/uv}
out=$root/runs/a100/branches
mkdir -p "$out"
log() { echo "[$(date -u +%FT%TZ)] branches: $*" | tee -a "$out/branches.log"; }
# shellcheck source=/dev/null
[[ ! -f $node/env.sh ]] || source "$node/env.sh"
flags="--max-priority-preemptions-per-step 2 --priority-prefill-budget-cap --priority-prefill-budget-cap-tokens 48"

case $action in
  stage)
    base=${2:?usage: branches.sh stage BASE HEAD} head=${3:?usage: branches.sh stage BASE HEAD}
    clone=$root/vendor/vllm
    [[ -d $clone/.git ]] || git clone -q --filter=blob:none https://github.com/StevenWang-CY/vllm.git "$clone"
    git -C "$clone" remote get-url upstream >/dev/null 2>&1 ||
      git -C "$clone" remote add upstream https://github.com/vllm-project/vllm.git
    git -C "$clone" fetch -q origin
    git -C "$clone" fetch -q upstream main
    case $(cat "$root/venvs/engine/flatshare-install-path" 2>/dev/null) in
      cu129) backend=cu129 ;;
      *) backend=cu130 ;;
    esac
    for pair in "base:$base" "head:$head"; do
      name=${pair%%:*} commit=${pair#*:}
      tree=$root/vendor/vllm-$name venv=$root/venvs/branch-$name
      [[ -d $tree ]] || git -C "$clone" worktree add -q --detach "$tree" "$commit"
      git -C "$tree" checkout -q --detach "$commit"
      [[ -x $venv/bin/python ]] || "$uv" venv -q --python 3.12 "$venv"
      log "$name: vLLM at $(git -C "$tree" rev-parse --short HEAD), precompiled binaries, torch for $backend"
      (cd "$tree" && VLLM_USE_PRECOMPILED=1 "$uv" pip install -q --python "$venv/bin/python" --torch-backend "$backend" -e .)
      echo "$commit" >"$venv/flatshare-commit"
    done
    # Each env parses the node's engine.yaml, and HEAD's knows the PRs' flags, before a GPU minute is spent.
    for name in base head; do
      extra=""
      [[ $name == base ]] || extra=$flags
      # shellcheck disable=SC2086 # the flags are words
      "$root/venvs/branch-$name/bin/python" - "$node/engine.yaml" $extra <<'PY'
import sys
try:  # vLLM 0.32.0's module, or the one earlier releases used
    from vllm.entrypoints.launchers.cli_args import make_arg_parser
except ImportError:
    from vllm.entrypoints.openai.cli_args import make_arg_parser
from vllm.utils.argparse_utils import FlexibleArgumentParser
parser = make_arg_parser(FlexibleArgumentParser(prog="vllm serve"))
args = parser.parse_args(["--config", sys.argv[1], *sys.argv[2:]])
print("parsed:", args.model, args.max_num_batched_tokens, getattr(args, "max_priority_preemptions_per_step", None))
PY
    done
    log "staged: base at $base, head at $head"
    ;;
  run)
    if [[ ${2:-} == --flags ]]; then flags=${3:?usage: branches.sh run [--flags "FLAG..."]}; fi
    probes=$src/python/flatshare_vllm/src/flatshare_vllm/make-room
    engine=unix:${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/flatshare/engine.sock # the engine's own socket
    for name in base head; do
      venv=$root/venvs/branch-$name
      [[ -f $venv/flatshare-commit ]] || { log "no $venv (branches.sh stage BASE HEAD)"; exit 2; }
      variant=$node/variants/branch-$name
      mkdir -p "$variant"
      cat >"$variant/flatshare-engine.conf" <<EOF
# Generated by benchmarks/a100/branches.sh: the engine from venvs/branch-$name, vLLM at $(cat "$venv/flatshare-commit").
[Service]
Environment=VIRTUAL_ENV=%h/flatshare/venvs/branch-$name
ExecStart=
ExecStart=%h/flatshare/venvs/branch-$name/bin/vllm serve --config $node/engine.yaml --uds \${FLATSHARE_ENGINE_SOCKET} \$FLATSHARE_ENGINE_FLAGS
EOF
      engine_flags=""
      [[ $name == base ]] || engine_flags=$flags
      log "$name: variant branch-$name ${engine_flags:-with no flag}"
      # shellcheck disable=SC2086 # the flags are words
      bash "$node/variant.sh" use "branch-$name" $engine_flags 2>&1 | tee -a "$out/branches.log"
      for run in kv-1 kv-2 kv-3 prefill-1 prefill-2 tail-1 tail-2; do
        file=$out/$name-$run
        [[ ! -f $file.txt ]] || continue
        case $run in
          tail-*) args=(tail.py "$engine" 240 pool fresh --reply 40) ;;
          *) args=(probe.py "$engine" "${run%-*}") ;;
        esac
        log "$name: $run"
        "$root/venvs/engine/bin/python" "$probes/${args[0]}" "${args[@]:1}" >"$file.partial" 2>&1 ||
          { log "$name: $run failed ($file.partial)"; exit 1; }
        mv "$file.partial" "$file.txt"
      done
    done
    bash "$node/variant.sh" use frozen 2>&1 | tee -a "$out/branches.log"
    log "complete"
    ;;
esac
