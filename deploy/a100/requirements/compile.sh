#!/usr/bin/env bash
# compile.sh: write engine-cu129.txt from engine-cu129.in, with every package that names no CUDA build held at the
# box's version (deploy/phastform/requirements/engine.txt), so that the two locks differ only in their CUDA builds.
# Run it after the box's lock changes, on any host (no GPU), with uv >= 0.11.27 (UV names another uv).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
box=$here/../../phastform/requirements/engine.txt
uv=${UV:-uv}
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
# The box's pins less those built per CUDA version: torch's family, vLLM, the CUDA Python bindings and toolkit
# metapackage, and NVIDIA's CUDA libraries (not nvidia-ml-py or the CUTLASS DSL, which carry both CUDA builds).
grep -E '^[a-z0-9]' "$box" |
  grep -vE '^(torch|torchaudio|torchvision|torchcodec|vllm|cuda-bindings|cuda-python|cuda-toolkit|cuda-tile)==' |
  grep -vE '^nvidia-(cublas|cuda|cudnn|cufft|cufile|curand|cusolver|cusparse|nccl|nvjitlink|nvshmem|nvtx|nvvm)' \
    >"$scratch/box.txt"
"$uv" pip compile -q --no-header --no-annotate --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --torch-backend cu129 --constraint "$scratch/box.txt" --output-file "$scratch/lock.txt" "$here/engine-cu129.in"
# The torch family's and vLLM's versions, less their CUDA builds, that are not the box's.
differ=
for name in torch torchaudio torchvision torchcodec vllm; do
  theirs=$(sed -n "s/^$name==\([^+]*\).*/\1/p" "$box")
  ours=$(sed -n -e "s/^$name==\([^+]*\).*/\1/p" -e "s/^$name @ .*\/$name-\([^+]*\)+.*/\1/p" "$scratch/lock.txt")
  [[ $ours == "$theirs" ]] || differ+="${differ:+, }$name $ours (the box's $theirs)"
done
{
  echo "# Engine environment for a GPU node whose driver is 525-579 (docs/HARDWARE.md): vLLM 0.32.0+cu129 with the audio"
  echo "# extra, torch 2.13.0+cu129, every other package at the box's version. Generated by compile.sh from"
  echo "# engine-cu129.in; built by deploy/a100/bootstrap.sh with: uv pip sync --torch-backend cu129"
  [[ -z $differ ]] || echo "# Not the box's version (CUDA 12.9's index has none that fits): $differ."
  cat "$scratch/lock.txt"
} >"$here/engine-cu129.txt"
echo "compile: wrote $here/engine-cu129.txt ($(grep -c '==\| @ ' "$here/engine-cu129.txt") packages)"
